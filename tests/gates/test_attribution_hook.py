"""TEST-python-TT01-06: commit-message hook and pull-request scan behaviour (RV-19(b)).

Runs on the Linux cells. Every attribution fixture is assembled from fragments
at run time, so no committed file holds an attribution line. The temporary
repository commits with an explicit identity, hooks disabled and signing off.
"""

from __future__ import annotations

import os
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

import pytest

HOOK = Path("tools/hooks/check-commit-msg.sh").resolve()
SCAN = Path("tools/hooks/scan-pull-request.sh").resolve()

pytestmark = pytest.mark.skipif(
    not sys.platform.startswith("linux"), reason="RV-19(b) runs on the Linux cells only"
)

TRAILER = "Co-" + "authored-by: "
REJECT = {
    "trailer naming the Claude assistant": TRAILER + "Cl" + "aude <noreply@example.com>",
    "trailer naming GitHub Copilot": TRAILER + "GitHub Co" + "pilot <copilot@example.com>",
    "robot line": "\U0001f916 " + "Generated " + "with [Cl" + "aude Code](https://example.com)",
    "generated-with line": "Generated " + "with Chat" + "GPT",
}
ACCEPT = {
    "human co-author": TRAILER + "Jane Doe <jane@example.com>",
    "generation mentioned": "Regenerate the lock file; this code was generated by a script.",
}


def _same(text: str) -> str:
    return text


CASES: tuple[Callable[[str], str], ...] = (str.upper, str.lower, str.swapcase, _same)


def _message(line: str) -> str:
    return f"Add a feature\n\nSome description.\n\n{line}\n"


def _hook(tmp_path: Path, text: str) -> int:
    message = tmp_path / "MSG"
    message.write_text(text, encoding="utf-8")
    return subprocess.run(
        ["sh", str(HOOK), str(message)], capture_output=True, check=False
    ).returncode


@pytest.mark.parametrize("name", sorted(REJECT))
def test_hook_rejects(tmp_path: Path, name: str) -> None:
    """The hook rejects each attribution line in any letter case."""
    for case in CASES:
        assert _hook(tmp_path, _message(case(REJECT[name]))) != 0, case


@pytest.mark.parametrize("name", sorted(ACCEPT))
def test_hook_accepts(tmp_path: Path, name: str) -> None:
    """The hook accepts a human co-author and a mere mention of generated code."""
    assert _hook(tmp_path, _message(ACCEPT[name])) == 0


def _git(repo: Path, *args: str) -> str:
    command = ["git", "-c", "core.hooksPath=", "-c", "commit.gpgsign=false", "-C", str(repo), *args]
    return subprocess.run(command, capture_output=True, text=True, check=True).stdout.strip()


def _repository(tmp_path: Path, messages: list[str]) -> tuple[Path, str, str]:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "user.name", "Test Person")
    _git(repo, "config", "user.email", "test@example.com")
    _git(repo, "commit", "-q", "--allow-empty", "--no-verify", "-m", "base")
    base = _git(repo, "rev-parse", "HEAD")
    for text in messages:
        _git(repo, "commit", "-q", "--allow-empty", "--no-verify", "-m", text)
    return repo, base, _git(repo, "rev-parse", "HEAD")


def _scan(tmp_path: Path, messages: list[str], title: str = "Title", body: str = "Body") -> int:
    repo, base, head = _repository(tmp_path, messages)
    env = {**os.environ, "PR_TITLE": title, "PR_BODY": body, "BASE_SHA": base, "HEAD_SHA": head}
    result = subprocess.run(["sh", str(SCAN)], cwd=repo, env=env, capture_output=True, check=False)
    return result.returncode


@pytest.mark.parametrize("name", sorted(REJECT))
def test_scan_rejects_in_a_commit_that_is_not_the_head(tmp_path: Path, name: str) -> None:
    """The scan reads every commit of the range, not only the head."""
    for index, case in enumerate(CASES):
        work = tmp_path / str(index)
        work.mkdir()
        messages = ["first", _message(case(REJECT[name])), "third"]
        assert _scan(work, messages) != 0, case


@pytest.mark.parametrize("name", sorted(REJECT))
def test_scan_rejects_in_title_or_body_only(tmp_path: Path, name: str) -> None:
    """The scan rejects an attribution line in the title alone and in the body alone."""
    (tmp_path / "title").mkdir()
    (tmp_path / "body").mkdir()
    assert _scan(tmp_path / "title", ["clean"], title=REJECT[name].upper()) != 0
    assert _scan(tmp_path / "body", ["clean"], body=_message(REJECT[name].lower())) != 0


def test_scan_accepts_clean_and_human_lines(tmp_path: Path) -> None:
    """The scan accepts a human co-author and a mere mention of generated code."""
    messages = [_message(ACCEPT["human co-author"]), _message(ACCEPT["generation mentioned"])]
    assert _scan(tmp_path, messages, body=ACCEPT["generation mentioned"]) == 0
